     * 税額 = floor(課税対象 × rate − deduction)。甲欄の課税対象は 社保控除後 − 扶養控除×人数。
     * ※内蔵既定と同一の係数を投入（適用期間管理・差し替えの土台）。実運用前に官報値と突合すること。
     */
    private function seedIncomeTaxBrackets(): void
    {
        $from = '2020-01-01';
        $depDeduction = 31667;

        // [min, max(nullは∞), rate, deduction]
        $kou = [
            [0, 88000, 0.0000, 0],
            [88000, 162500, 0.0500, 4400],
            [162500, 275000, 0.1000, 12525],
            [275000, 579000, 0.2000, 40025],
            [579000, 750000, 0.2300, 57395],
            [750000, 1500000, 0.3300, 132395],
            [1500000, null, 0.4000, 237395],
        ];
        $otsu = [
            [0, 88000, 0.0300, 0],
            [88000, 740000, 0.3000, 20000],
            [740000, null, 0.4000, 94000],
        ];

        // 冪等化: 同一 tax_table + effective_from の旧行を一度消してから再投入
        IncomeTaxBracket::where('effective_from', $from)->delete();

        foreach ($kou as [$min, $max, $rate, $ded]) {
            IncomeTaxBracket::create([
                'tax_table' => 'kou', 'min_amount' => $min, 'max_amount' => $max,
                'rate' => $rate, 'deduction' => $ded, 'dependent_deduction' => $depDeduction,
                'effective_from' => $from, 'effective_to' => null,
            ]);
        }
        foreach ($otsu as [$min, $max, $rate, $ded]) {
            IncomeTaxBracket::create([
                'tax_table' => 'otsu', 'min_amount' => $min, 'max_amount' => $max,
                'rate' => $rate, 'deduction' => $ded, 'dependent_deduction' => null,
                'effective_from' => $from, 'effective_to' => null,
            ]);
        }
    }

